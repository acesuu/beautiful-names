"""Merge data/chapters/chNN.json into data.js (loaded by index.html via <script>, so the
site works when opened directly from disk without a web server)."""
import json, pathlib, sys

root = pathlib.Path(__file__).resolve().parent
chapters = []
for f in sorted((root / "data" / "chapters").glob("ch*.json")):
    ch = json.loads(f.read_text(encoding="utf-8"))
    for key in ("chapter", "names", "blocks", "keyPoints", "evidence", "recall"):
        if key not in ch:
            sys.exit(f"{f.name}: missing '{key}'")
    for n in ch["names"]:
        for key in ("translit", "arabic", "meaning"):
            if not n.get(key):
                sys.exit(f"{f.name}: name missing '{key}': {n}")
    chapters.append(ch)

chapters.sort(key=lambda c: c["chapter"])
nums = [c["chapter"] for c in chapters]
missing = sorted(set(range(1, 71)) - set(nums))
total = sum(len(c["names"]) for c in chapters)
(root / "data.js").write_text(
    "// Generated by build_data.py - do not edit by hand.\nwindow.BOOK = "
    + json.dumps({"chapters": chapters}, ensure_ascii=False, separators=(",", ":"))
    + ";\n",
    encoding="utf-8",
)
print(f"{len(chapters)} chapters, {total} names written to data.js")
if missing:
    print("MISSING chapters:", missing)
